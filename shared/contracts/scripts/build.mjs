#!/usr/bin/env node
/**
 * Contract codegen (P1-A-02, ADR-0016).
 * Generates committed TS + Dart types from openapi.yaml and schemas/rpc/*.json.
 */
import { cpSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { compileFromFile } from 'json-schema-to-typescript';

const require = createRequire(import.meta.url);

const __dirname = dirname(fileURLToPath(import.meta.url));
const pkgRoot = join(__dirname, '..');
const repoRoot = join(pkgRoot, '../..');
const generatedDir = join(pkgRoot, 'generated');
const schemasDir = join(pkgRoot, 'schemas');
const rpcDir = join(schemasDir, 'rpc');
const dartOut = join(
  repoRoot,
  'shared/flutter/along_data/lib/src/contracts/api_contracts.g.dart',
);

mkdirSync(generatedDir, { recursive: true });

const commonPath = join(schemasDir, 'common.json');
const commonSchema = JSON.parse(readFileSync(commonPath, 'utf8'));
const commonDefs = commonSchema.$defs ?? {};

/** Inline $ref to common.json or local #/$defs before json-schema-to-typescript. */
function deref(schema, localDefs = commonDefs) {
  if (schema === null || typeof schema !== 'object') return schema;
  if (Array.isArray(schema)) return schema.map((item) => deref(item, localDefs));
  if ('$ref' in schema && typeof schema.$ref === 'string') {
    const ref = schema.$ref;
    if (ref.includes('common.json#/$defs/')) {
      const name = ref.split('/').pop();
      return deref(structuredClone(commonDefs[name]), localDefs);
    }
    if (ref.startsWith('#/$defs/')) {
      const name = ref.split('/').pop();
      return deref(structuredClone(localDefs[name]), localDefs);
    }
  }
  const out = {};
  for (const [key, value] of Object.entries(schema)) {
    out[key] = deref(value, localDefs);
  }
  return out;
}

async function compileDef(name, def, localDefs, label) {
  const standalone = deref({
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: name,
    ...def,
  }, localDefs);
  const tmpPath = join(generatedDir, `.tmp-${label}-${name}.json`);
  writeFileSync(tmpPath, JSON.stringify(standalone, null, 2));
  return compileFromFile(tmpPath, {
    bannerComment: '',
    additionalProperties: false,
    enableConstEnums: true,
  });
}

// --- OpenAPI → TS ---
const openapiPath = join(pkgRoot, 'openapi.yaml');
const edgeOut = join(generatedDir, 'edge.ts');
const openapiCli = require.resolve('openapi-typescript/bin/cli.js');
execFileSync(process.execPath, [openapiCli, openapiPath, '-o', edgeOut], {
  stdio: 'inherit',
});

// --- JSON Schema RPC → TS ---
const rpcParts = [
  '/** Generated by @along/contracts build — do not edit. */',
  '',
  '/* eslint-disable */',
  '',
];

const rpcFiles = readdirSync(rpcDir)
  .filter((f) => f.endsWith('.json') && f !== 'manifest.json')
  .sort();

for (const file of rpcFiles) {
  const schemaPath = join(rpcDir, file);
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
  if (!schema.$defs) continue;
  for (const [name, def] of Object.entries(schema.$defs)) {
    const ts = await compileDef(name, def, { ...commonDefs, ...schema.$defs }, file);
    rpcParts.push(`/** ${file} → ${name} */`);
    rpcParts.push(ts.trim());
    rpcParts.push('');
  }
}

writeFileSync(join(generatedDir, 'rpc.ts'), `${rpcParts.join('\n')}\n`);

// --- Common JSON Schema → TS ---
const commonParts = [
  '/** Generated by @along/contracts build — do not edit. */',
  '',
  '/* eslint-disable */',
  '',
];
for (const [name, def] of Object.entries(commonDefs)) {
  const ts = await compileDef(name, def, commonDefs, 'common');
  commonParts.push(`/** common.json → ${name} */`);
  commonParts.push(ts.trim());
  commonParts.push('');
}
writeFileSync(join(generatedDir, 'common.ts'), `${commonParts.join('\n')}\n`);

// --- Dart generation ---
execFileSync(process.execPath, [join(__dirname, 'generate_dart.mjs')], {
  stdio: 'inherit',
});

console.log('Contracts built: generated/{edge,rpc,common}.ts + along_data Dart types.');
